import axios from 'axios';

/**
 * DYNAMIC API URL SELECTION
 * In development (localhost), it uses the local FastAPI server.
 * In production (Vercel), it reads the URL from the environment variable 'VITE_API_URL'.
 */
const API_BASE_URL = import.meta.env.VITE_API_URL || 'http://localhost:8000';

// Create a pre-configured Axios instance
const API = axios.create({
    baseURL: API_BASE_URL,
});

/**
 * AXIOS REQUEST INTERCEPTOR
 * This runs before every request. Useful for global configurations 
 * like adding auth headers or logging requests.
 */
API.interceptors.request.use((config) => {
    return config;
}, (error) => {
    return Promise.reject(error);
});

/**
 * FETCH TRANSACTIONS
 * Retrieves all categorized and uncategorized expenses for a specific user.
 * @param {string} userId - The unique ID of the logged-in user.
 */
export const fetchTransactions = async (userId) => {
    if (!userId) return [];
    try {
        const response = await API.get(`/api/transactions?user_id=${userId}`);
        return response.data;
    } catch (error) {
        console.error("Error fetching transactions:", error);
        return [];
    }
};

/**
 * FETCH FORECAST
 * Retrieves predictive spending data generated by the Meta Prophet AI model.
 * @param {string} userId - Current user's ID.
 * @param {number} days - Prediction horizon (default 30 days).
 * @param {string} category - Specific category filter (default 'All').
 * @param {string} bank - Specific bank filter (default 'All').
 * @param {string} type - 'Expenses' or 'Income'.
 */
export const fetchForecast = async (userId, days = 30, category = 'All', bank = 'All', type = 'Expenses') => {
    if (!userId) return { error: "User ID missing" };
    try {
        const response = await API.get(`/api/forecast`, {
            params: { user_id: userId, days, category, bank, type }
        });
        return response.data;
    } catch (error) {
        console.error("Error fetching forecast:", error);
        return { error: "Failed to fetch forecast" };
    }
};

/**
 * UPLOAD BANK FILE
 * Sends a CSV or Excel statement to the backend for extraction and AI classification.
 * Uses FormData for multipart/form-data support.
 */
export const uploadBankFile = async (file, bankName, userId) => {
    if (!userId) throw new Error("User ID missing");
    
    const formData = new FormData();
    formData.append('file', file);
    formData.append('bank', bankName);
    formData.append('user_id', userId); 

    try {
        const response = await API.post('/api/upload', formData, {
            // Important for file uploads: inform Axios to use multipart headers
            headers: { 'Content-Type': 'multipart/form-data' },
        });
        return response.data;
    } catch (error) {
        console.error("Upload Error:", error.response?.data || error.message);
        throw error;
    }
};

/**
 * UPDATE TRANSACTION CATEGORY
 * Manually changes a transaction's category in the DB.
 * This also triggers the AI retraining event on the backend.
 */
export const updateTransactionCategory = async (txId, category) => {
    try {
        const response = await API.put(`/api/transactions/${txId}`, { category });
        return response.data;
    } catch (error) {
        console.error("Update Error:", error.response?.data || error.message);
        throw error;
    }
};

/**
 * DELETE BANK DATA
 * Removes all records associated with a specific bank for the current user.
 */
export const deleteBankData = async (userId, bankName) => {
    try {
        // Query parameters matched to the FastAPI delete endpoint
        const response = await API.delete(`/api/clear_bank?user_id=${userId}&bank_name=${bankName}`);
        return response.data;
    } catch (error) {
        console.error("Delete Error:", error.response?.data || error.message);
        throw error;
    }
};

export default API;